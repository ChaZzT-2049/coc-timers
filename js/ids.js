export function resolveName(dataId, village) {
  const id = Number(dataId);
  if (village === "builder" && BUILDER_NAMES[id]) return BUILDER_NAMES[id];
  if (village === "home" && HOME_NAMES[id]) return HOME_NAMES[id];
  return HOME_NAMES[id] || BUILDER_NAMES[id] || UNIT_NAMES[id] || `ID ${id}`;
}

export function isKnownId(dataId) {
  const id = Number(dataId);
  return Boolean(HOME_NAMES[id] || BUILDER_NAMES[id] || UNIT_NAMES[id]);
}

function catalogRows(map) {
  return Object.entries(map)
    .map(([id, name]) => ({ id: Number(id), name }))
    .sort((a, b) => a.id - b.id);
}

/** Listas editables en js/ids.js: edificios, base y tropas/hechizos/héroes. */
export function nameCatalog() {
  return [
    { id: "home", title: "Aldea principal", rows: catalogRows(HOME_NAMES) },
    { id: "builder", title: "Base de constructores", rows: catalogRows(BUILDER_NAMES) },
    { id: "units", title: "Tropas, hechizos, héroes y mascotas", rows: catalogRows(UNIT_NAMES) },
  ];
}

export function helperIdForKind(kind, village = "home") {
  if (village !== "home") return null;
  if (kind === "lab" || kind === "workshop") return HELPER_LAB;
  if (kind === "builder" || kind === "trap" || kind === "hero") return HELPER_APPRENTICE;
  return null;
}

export function kindFromFieldAndId(field, dataId) {
  const id = Number(dataId);
  if (field === "pets") return "pet";
  if (field === "heroes" || field === "heroes2") return "hero";
  if (field === "traps" || field === "traps2") return "trap";
  if (field === "helpers") return "helper";
  if (field === "units2" || field === "spells2") return "starlab";
  if (SIEGE_IDS.has(id) || field === "siege") return "workshop";
  if (field === "units" || field === "spells") return "lab";
  if (id >= 73000000 && id < 74000000) return "pet";
  if (id >= 28000000 && id < 29000000) return "hero";
  if (id >= 26000000 && id < 27000000) return "lab";
  if (id >= 12000000 && id < 13000000) return "trap";
  return "builder";
}
